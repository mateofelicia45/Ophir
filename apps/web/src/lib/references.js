const BOOK_BY_NAME = new Map(
  BOOKS.map((b) => [b.name.toLowerCase(), b])
);

const NUMBER_WORDS = {
  i: '1',
  ii: '2',
  iii: '3',
  primero: '1',
  segundo: '2',
  tercer: '3',
};

export function findBook(name) {
  if (!name) return null;
  const clean = String(name).trim().toLowerCase();
  const direct = BOOK_BY_NAME.get(clean);
  if (direct) return direct;
  return BOOKS.find(
    (b) =>
      b.abbr.toLowerCase() === clean ||
      b.id === clean ||
      b.name.toLowerCase().startsWith(clean)
  ) || null;
}

export function parseReference(text) {
  const match = String(text).trim().match(
    /^((?:[1-3]\s*|I{1,3}\s*)?[^0-9]+?)\s*(\d+)(?::(\d+)(?:[-–](\d+))?)?$/
  );
  if (!match) return null;

  let bookName = match[1].trim();
  for (const [word, num] of Object.entries(NUMBER_WORDS)) {
    bookName = bookName.replace(new RegExp(`\\b${word}\\b`, 'i'), num);
  }
  bookName = bookName.replace(/\./g, '').replace(/\s+/g, ' ').trim();

  const book = findBook(bookName);
  if (!book) return null;
  if (Number(match[2]) > book.chapters) return null;

  return {
    book,
    chapter: Number(match[2]),
    verseStart: match[3] ? Number(match[3]) : null,
    verseEnd: match[4] ? Number(match[4]) : null,
  };
}

export function formatReference({ book, chapter, verseStart, verseEnd }, style = 'long') {
  const label = style === 'abbr' ? book.abbr : book.name;
  let ref = `${label} ${chapter}`;
  if (verseStart) ref += `:${verseStart}`;
  if (verseEnd) ref += `-${verseEnd}`;
  return ref;
}
